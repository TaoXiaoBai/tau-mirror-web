const DICTS = { en, zh };
const listeners = new Set();

function detectSystemLocale() {
  const langs = [...(navigator.languages || []), navigator.language, navigator.userLanguage].filter(Boolean);
  return langs.some((item) => String(item).toLowerCase().startsWith('zh')) ? 'zh' : 'en';
}

export function getLocalePreference() {
  const saved = localStorage.getItem(STORAGE_KEY);
  if (saved === 'en' || saved === 'zh' || saved === 'auto') return saved;
  return 'auto';
}

export function getLocale() {
  const pref = getLocalePreference();
  return pref === 'auto' ? detectSystemLocale() : pref;
}

export function t(key, vars = {}) {
  const locale = getLocale();
  const table = DICTS[locale] || en;
  let text = table[key] ?? en[key] ?? key;
  for (const [name, value] of Object.entries(vars)) {
    text = text.replaceAll(`{${name}}`, String(value ?? ''));
  }
  return text;
}

export function applyDomTranslations(root = document) {
  document.documentElement.lang = getLocale() === 'zh' ? 'zh-CN' : 'en';
  document.title = t('title');
  root.querySelectorAll('[data-i18n]').forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
  root.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    el.setAttribute('placeholder', t(el.dataset.i18nPlaceholder));
  });
  root.querySelectorAll('[data-i18n-title]').forEach((el) => {
    el.setAttribute('title', t(el.dataset.i18nTitle));
  });
  root.querySelectorAll('[data-i18n-aria]').forEach((el) => {
    el.setAttribute('aria-label', t(el.dataset.i18nAria));
  });
}

export function setLocalePreference(pref) {
  if (pref === 'en' || pref === 'zh') localStorage.setItem(STORAGE_KEY, pref);
  else localStorage.setItem(STORAGE_KEY, 'auto');
  applyDomTranslations();
  listeners.forEach((fn) => fn(getLocale()));
}

export function onLocaleChange(fn) {
  listeners.add(fn);
  return () => listeners.delete(fn);
}

